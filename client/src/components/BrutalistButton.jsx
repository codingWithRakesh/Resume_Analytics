function joinClassNames(...classNames) {
  return classNames.filter(Boolean).join(' ')
}

export default function BrutalistButton({
  variant = 'primary',
  className,
  type = 'button',
  children,
  icon,
  iconPosition = 'right',
  iconClassName,
  density = 'default',
  ...props
}) {
  const hasIcon = Boolean(icon)
  const isCompact = density === 'compact' || density === 'profile'
  const variantClassName =
    variant === 'secondary'
      ? density === 'profile'
        ? hasIcon && iconPosition === 'right'
          ? profileSecondaryIconClassName
          : profileSecondaryClassName
        : isCompact
          ? hasIcon && iconPosition === 'right'
            ? compactSecondaryIconClassName
            : compactSecondaryClassName
          : hasIcon && iconPosition === 'right'
            ? secondaryIconClassName
            : secondaryClassName
      : density === 'profile'
        ? hasIcon && iconPosition === 'right'
          ? profilePrimaryIconClassName
          : profilePrimaryClassName
        : isCompact
          ? hasIcon && iconPosition === 'right'
            ? compactPrimaryIconClassName
            : compactPrimaryClassName
          : hasIcon && iconPosition === 'right'
            ? primaryIconClassName
            : primaryClassName

  return (
    <button
      type={type}
      className={joinClassNames(variantClassName, className)}
      {...props}
    >
      {hasIcon && iconPosition === 'right' ? (
        <>
          <span className="pointer-events-none" aria-hidden="true" />
          <span className="justify-self-center">{children}</span>
          <span className={joinClassNames('justify-self-end', iconClassName)}>{icon}</span>
        </>
      ) : hasIcon && iconPosition === 'left' ? (
        <>
          <span className={joinClassNames('justify-self-start', iconClassName)}>{icon}</span>
          <span className="justify-self-center">{children}</span>
          <span className="pointer-events-none" aria-hidden="true" />
        </>
      ) : (
        children
      )}
    </button>
  )
}
